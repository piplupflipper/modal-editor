// Command widthgen は、internal/ui の表示幅の表（widetable.go）と、その検査に使う Vim の値（testdata/vim-width.txt）を作り直す。
//
// internal/ui のディレクトリで `go generate` を打つと動く（width.go の go:generate）。
// PATH にある vim を `vim -Nu NONE -es` で起動して width.vim を読み込ませ、
// U+0001 から U+10FFFF までの全文字の表示幅を Vim の strdisplaywidth() で求める（数秒かかる）。
// Vim か Unicode の版を上げたときに打ち直し、`go test ./internal/ui` で差分を確かめる。
//
// 2026-11-16 に Vim 9.1（パッチ 1-16）で作った。
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
)

// interval は、Vim の値の 1 つの区間である。
type interval struct {
	lo, hi       rune
	after, alone int // 'a' の後に置いた幅と、単独の幅
}

func main() {
	log.SetFlags(0)
	_, self, _, ok := runtime.Caller(0)
	if !ok {
		log.Fatal("widthgen: cannot locate source directory")
	}
	script := filepath.Join(filepath.Dir(self), "width.vim")
	out := filepath.Join("testdata", "vim-width.txt")

	cmd := exec.Command("vim", "-Nu", "NONE", "-es", "-S", script) //nolint:gosec // script はこのコマンドのソースの隣の width.vim で、利用者の入力ではない
	cmd.Env = append(os.Environ(), "WIDTHGEN_OUT="+out)
	if err := cmd.Run(); err != nil {
		log.Fatalf("widthgen: vim: %v", err)
	}
	data, err := os.ReadFile(out)
	if err != nil {
		log.Fatal(err)
	}
	var ivs []interval
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		var iv interval
		if _, serr := fmt.Sscanf(sc.Text(), "%x %x %d %d", &iv.lo, &iv.hi, &iv.after, &iv.alone); serr != nil {
			log.Fatalf("widthgen: %q: %v", sc.Text(), serr)
		}
		ivs = append(ivs, iv)
	}

	var b bytes.Buffer
	b.WriteString(`// Code generated by internal/ui/internal/widthgen; DO NOT EDIT.

package ui

// wideTable は、表示幅が 2 列の文字の区間（両端を含む）を、小さい順に並べた表である。
//
// Vim の strdisplaywidth('a' .. c) - 1 が 2 になる区間のうち U+00A0 以降のものを写した。
// Vim の East Asian Width の表（Wide と Fullwidth）と、絵文字を 2 列にする表を重ねた結果に当たる。
var wideTable = [...][2]rune{
`)
	for _, iv := range ivs {
		if iv.after == 2 && iv.lo >= 0xa0 {
			fmt.Fprintf(&b, "\t{0x%04X, 0x%04X},\n", iv.lo, iv.hi)
		}
	}
	b.WriteString(`}

// loneComposingTable は、行頭に単独で置いた結合文字の表示幅が 1 でない区間と、その幅である。
//
// Vim の strdisplaywidth('a' .. c) - 1 が 0（結合文字）で、strdisplaywidth(c) が 1 でない区間を写した。
// 幅 2 は全角の結合文字（U+3099 など）、それより大きい幅は <180b> の形で出す文字である。
var loneComposingTable = [...]struct {
	lo, hi rune
	width  int
}{
`)
	for _, iv := range ivs {
		if iv.after == 0 && iv.alone != 1 && iv.lo >= 0xa0 {
			fmt.Fprintf(&b, "\t{0x%04X, 0x%04X, %d},\n", iv.lo, iv.hi, iv.alone)
		}
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("widetable.go", src, 0o600); err != nil {
		log.Fatal(err)
	}
}

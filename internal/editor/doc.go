// Package editor は、本体のイベントループである（基本設計 2 章、2.1）。
// 部品（internal/buffer、internal/command、internal/input、internal/ui、internal/exthost）をつなぎ、
// 端末からのキー入力と、拡張機能からのメッセージを 1 件ずつ処理する。
//
// # 差し込みの口
//
// 端末の制御のライブラリと設定ファイル（JSONC）は #9 で裁定待ちなので、このパッケージは次の口で受ける。
//
//   - 端末: Terminal。キーとリサイズのイベントをチャネルで送り、ui の格子（Screen）を受け取って出す
//   - 設定: Config。キーマップ（基本設計 7 章の keymap）、期限（syncTimeoutMs）、宣言ファイルの一覧などを値で受ける。
//     ゼロ値の項目は既定値で動く
//
// # 並行処理
//
// 編集の状態（バッファ、モード、レジスター、表示のデータ）は、Run を呼んだ goroutine だけが触る（基本設計 2.1）。
// 端末の入力は、このパッケージの中の goroutine が読んで列に積み、拡張機能のイベントは exthost.Host.Events から受ける。
// 列に積む goroutine は、中断のキー（<C-c>）を見たら印を立てる。
// マクロの再生（999999999@:）は Feed の中で同期に進むので、command.State.Interrupted でこの印を読ませて止める。
//
// # 拡張機能への問い合わせ
//
// キー入力ごとに結果が要る問い合わせ（基本設計 5.4）は、command.Extensions の実装として exthost.Host.Send で送る。
//
//   - 期限が正の値（FR-17）: 結果か期限の超過を、入れ子の待ち（wait）で待つ。待つ間も、リサイズに応じて描画し、
//     <C-c> で問い合わせを取り消す。拡張機能からのイベントは取っておき、待ちが終わってから届いた順に処理する
//   - 期限が 0（FR-18）: 送って command.ErrDeferred を返し、次のキー入力を受け付ける。
//     結果が届いたら command.State.ApplyDeferred で、バージョン番号とカーソルが問い合わせたときと同じ場合だけ適用する
//   - マクロとドットリピートの再生中（FR-19）: 期限の設定に関わらず入れ子の待ちで待つ。
//     上限（Config.ReplayTimeout）を超えるか <C-c> で取り消すと、その操作が失敗し、再生はそこで止まる
//
// 入れ子の待ちの間は、どの拡張機能からのリクエストと通知も処理せずに取っておく。
// 基本設計 5.3 は、待っている拡張機能からのリクエストだけを待たせると定めるが、
// 待ちは command.State の操作の途中なので、他の拡張機能の buffer/edit をその間に適用すると、操作の途中でバッファが変わる。

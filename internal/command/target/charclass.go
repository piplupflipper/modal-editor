import "sort"

// 文字の分類（Vim の cls() と utf_class() の戻り値）。
// 分類が同じ文字の並びを 1 つの単語として扱い、分類が変わる位置を単語の境目にする。
// classBlank、classPunct、classWord 以外の値は、Vim と同じく、その文字の区画の先頭の符号位置である。
const (
	classBlank     = 0      // 空白、タブ、行末の位置、全角空白（U+3000）などの Unicode の空白
	classPunct     = 1      // 単語の文字でない記号。W などでは空白以外の全て
	classWord      = 2      // 英数字、_、ラテン文字など、下の表に無い文字
	classEmoji     = 3      // 絵文字
	classBraille   = 0x2800 // 点字
	classHiragana  = 0x3040 // ひらがな
	classKatakana  = 0x30a0 // カタカナ
	classIdeograph = 0x4e00 // 漢字（CJK 統合漢字とその拡張、互換漢字）
	classHangul    = 0xac00 // ハングルの音節
)

// classOf は、文字の分類を返す。big が true なら、W などのための分類（空白か、それ以外か）を返す。
//
// Vim 9.1（パッチ 1-16）の src/textobject.c の cls() と、src/mbyte.c の utf_class() に相当する。
// 'encoding' が utf-8 で、'iskeyword' が既定（@,48-57,_,192-255）のときの値を返す。
//
//   - U+00FF までは、空白、タブ、NBSP（U+00A0）を空白とし、'iskeyword' の既定に入る文字（英数字、_、µ、U+00C0 から U+00FF）を単語の文字とし、残りを記号とする
//   - U+0100 からは、表 wideClasses にあればその分類、無ければ単語の文字とする
//   - big が true なら、空白でない文字はすべて記号とする（全角空白は W でも空白）
//
// 文字の 0 は行末の位置を表し、空白とする。
// 結合文字と不正な UTF-8 のバイトの扱いは、呼び出し側の cursor.cls が Vim に合わせる。
func classOf(r rune, big bool) int {
	var class int
	switch {
	case r == 0 || r == ' ' || r == '\t' || r == 0xa0:
		class = classBlank
	case r < 0x100:
		if r == '_' || r == 0xb5 || r >= 0xc0 ||
			'0' <= r && r <= '9' || 'a' <= r && r <= 'z' || 'A' <= r && r <= 'Z' {
			class = classWord
		} else {
			class = classPunct
		}
	default:
		class = wideClass(r)
	}
	if big && class != classBlank {
		return classPunct
	}
	return class
}

// wideClass は、U+0100 以降の文字の分類を表 wideClasses から引く。
func wideClass(r rune) int {
	i := sort.Search(len(wideClasses), func(i int) bool {
		return wideClasses[i].last >= r
	})
	if i < len(wideClasses) && wideClasses[i].first <= r {
		return wideClasses[i].class
	}
	return classWord
}

